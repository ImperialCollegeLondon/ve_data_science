def output_summary_by_response(data: dict, spec: dict) -> pd.DataFrame:
    """Distribution of every scalar response across the runs."""
    variable = {r["name"]: r["variable"] for r in spec["responses"]}
    statistic = {r["name"]: r["statistic"] for r in spec["responses"]}
    rows = []
    for column, name in enumerate(data["scalar_names"]):
        name = str(name)
        values = data["scalars"][:, column]
        p05, median, p95 = np.quantile(values, [0.05, 0.5, 0.95])
        mean = values.mean()
        rows.append(
            {
                "response": name,
                "group": str(data["scalar_groups"][column]),
                "variable": variable[name],
                "statistic": statistic[name],
                "unit": unit_of(variable[name]),
                "n_runs": len(values),
                "min": values.min(),
                "p05": p05,
                "median": median,
                "mean": mean,
                "p95": p95,
                "max": values.max(),
                "cv_across_runs": float(relative(values.std(ddof=1), mean)),
                "p95_over_p05": float(relative(p95, p05)) if p05 > 0 else np.nan,
                "n_runs_negative": int((values < -near_zero).sum()),
                "n_runs_zero": int((np.abs(values) <= near_zero).sum()),
            }
        )
    return pd.DataFrame(rows)


def outlet_mask(data: dict) -> np.ndarray:
    """Boolean (ny, nx) mask of the outlet cells used for the "outlet" fields."""
    x, y = data["x"], data["y"]
    mask = np.zeros((len(y), len(x)), dtype=bool)
    for x_outlet, y_outlet in np.asarray(data["outlet_xy"], dtype=float):
        if np.isfinite(x_outlet) and np.isfinite(y_outlet):
            mask[np.argmin(np.abs(y - y_outlet)), np.argmin(np.abs(x - x_outlet))] = 1
    return mask


def output_spatial_summary(data: dict, spec: dict) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Long-term-mean maps: per-field summary and per-cell ensemble spread.

    ``data["maps"]`` is (runs, fields, y, x): each run's post-spin-up mean. The
    ensemble-median map is the median over runs in every cell.
    """
    x, y = data["x"], data["y"]
    outlets = outlet_mask(data)
    rows, cells = [], []
    for index, field in enumerate(data["fields"]):
        field = str(field)
        maps = data["maps"][:, index]
        p05, median, p95 = np.quantile(maps, [0.05, 0.5, 0.95], axis=0)
        row, col = np.unravel_index(np.argmax(median), median.shape)
        spread = relative(p95 - p05, median)
        rows.append(
            {
                "field": field,
                "rule": spec["fields"][field],
                "unit": unit_of(field),
                "cell_min": median.min(),
                "cell_median": np.median(median),
                "cell_max": median.max(),
                "spatial_cv": float(relative(median.std(ddof=1), median.mean())),
                "max_cell_x": x[col],
                "max_cell_y": y[row],
                "max_cell_is_outlet": bool(outlets[row, col]),
                "outlet_over_domain_mean": (
                    float(relative(median[outlets].mean(), median.mean()))
                    if outlets.any()
                    else np.nan
                ),
                "n_cells_negative_median_map": int((median < -near_zero).sum()),
                "n_runs_any_negative_cell": int(
                    (maps < -near_zero).any(axis=(1, 2)).sum()
                ),
                "between_run_spread_median": (
                    float(np.nanmedian(spread)) if np.isfinite(spread).any() else np.nan
                ),
            }
        )
        for r in range(len(y)):
            for c in range(len(x)):
                cells.append(
                    {
                        "field": field,
                        "x": x[c],
                        "y": y[r],
                        "is_outlet": bool(outlets[r, c]),
                        "p05": p05[r, c],
                        "median": median[r, c],
                        "p95": p95[r, c],
                    }
                )
    return pd.DataFrame(rows), pd.DataFrame(cells)


def output_temporal_summary(data: dict) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Monthly series: seasonality, drift and sign, per field.

    ``data["series"]`` is (runs, fields, months) after spin-up: the outlet sum
    for "outlet" fields and the domain mean for the others. Drift is the slope
    of each run's annual means, times the length of the period, relative to that
    run's mean: a store at steady state has a drift near zero.
    """
    dates = pd.to_datetime([str(d) for d in data["dates"]], format="%Y-%m")
    years = np.asarray(dates.year)
    months = np.asarray(dates.month)
    unique_years = np.unique(years)
    rows, climatology_rows = [], []
    for index, field in enumerate(data["fields"]):
        field = str(field)
        series = data["series"][:, index]  # (runs, months)
        run_mean = series.mean(axis=1)
        climatology = np.stack(
            [series[:, months == m].mean(axis=1) for m in range(1, 13)], axis=1
        )  # (runs, 12)
        clim_median = np.median(climatology, axis=0)
        annual = np.stack(
            [series[:, years == year].mean(axis=1) for year in unique_years], axis=1
        )
        slopes = np.polyfit(unique_years, annual.T, 1)[0]  # per run, unit per year
        span = unique_years[-1] - unique_years[0]
        drift = relative(slopes * span, run_mean)
        rows.append(
            {
                "field": field,
                "unit": unit_of(field),
                "median_of_run_means": float(np.median(run_mean)),
                "peak_month": month_names[int(np.argmax(clim_median))],
                "low_month": month_names[int(np.argmin(clim_median))],
                "seasonal_range_rel": float(
                    relative(clim_median.max() - clim_median.min(), np.median(run_mean))
                ),
                "median_trend_per_year": float(np.median(slopes)),
                "median_drift_rel": float(np.nanmedian(drift)),
                "n_runs_rising": int((drift > drift_flag).sum()),
                "n_runs_falling": int((drift < -drift_flag).sum()),
                "share_months_negative": float((series < -near_zero).mean()),
                "median_month_to_month_cv": float(
                    np.nanmedian(relative(series.std(axis=1, ddof=1), run_mean))
                ),
            }
        )
        p05, median, p95 = np.quantile(climatology, [0.05, 0.5, 0.95], axis=0)
        for m in range(12):
            climatology_rows.append(
                {
                    "field": field,
                    "month": month_names[m],
                    "p05": p05[m],
                    "median": median[m],
                    "p95": p95[m],
                }
            )
    return pd.DataFrame(rows), pd.DataFrame(climatology_rows)


def plot_output_overview(data: dict, spec: dict, figures: Path) -> None:
    """Three overview figures of the output variables across all runs."""
    plt = pyplot()
    colour = categorical_colours[0]
    fields = [str(f) for f in data["fields"]]
    n_runs = data["scalars"].shape[0]

    def grid(n_panels, width=3.4, height=2.4, n_cols=4):
        n_rows = int(np.ceil(n_panels / n_cols))
        fig, axes = plt.subplots(
            n_rows, n_cols, figsize=(width * n_cols, height * n_rows), squeeze=False
        )
        for axis in axes.flat[n_panels:]:
            axis.set_visible(False)
        return fig, axes.flat

    # Scalar responses across the runs
    names = [str(n) for n in data["scalar_names"]]
    variable = {r["name"]: r["variable"] for r in spec["responses"]}
    fig, axes = grid(len(names), height=1.8)
    for column, (axis, name) in enumerate(zip(axes, names)):
        values = data["scalars"][:, column]
        axis.boxplot(
            values,
            orientation="horizontal",
            widths=0.5,
            whis=(5, 95),
            patch_artist=True,
            boxprops={"facecolor": colour, "alpha": 0.35, "edgecolor": colour},
            medianprops={"color": colour, "linewidth": 2},
            flierprops={"marker": "o", "markersize": 3, "markeredgecolor": colour},
        )
        if values.min() > 0 and values.max() / values.min() > 100:
            axis.set_xscale("log")
        axis.set_title(name, fontsize=9)
        axis.set_yticks([])
        if axis.get_xscale() == "linear":
            axis.ticklabel_format(axis="x", useOffset=False)
        axis.set_xlabel(unit_of(variable[name]), fontsize=8)
        axis.tick_params(labelsize=7)
    fig.suptitle(f"Responses across {n_runs} runs (box 25-75%, whiskers 5-95%)")
    fig.tight_layout()
    save_figure(fig, figures / "06_output_distributions.png")

    # Monthly series: ensemble median and 5-95% band
    dates = pd.to_datetime([str(d) for d in data["dates"]], format="%Y-%m")
    fig, axes = grid(len(fields), width=3.6, height=2.3)
    for index, (axis, field) in enumerate(zip(axes, fields)):
        series = data["series"][:, index]
        p05, median, p95 = np.quantile(series, [0.05, 0.5, 0.95], axis=0)
        axis.fill_between(dates, p05, p95, color=colour, alpha=0.2, linewidth=0)
        axis.plot(dates, median, color=colour, linewidth=1.5)
        rule = spec["fields"][field]
        axis.set_title(f"{field} ({rule})", fontsize=8)
        axis.set_ylabel(unit_of(field), fontsize=8)
        axis.ticklabel_format(axis="y", useOffset=False)
        axis.tick_params(labelsize=7)
        axis.grid(alpha=0.3)
    fig.suptitle(f"Monthly series: median and 5-95% range over {n_runs} runs")
    fig.tight_layout()
    save_figure(fig, figures / "07_output_monthly_series.png")

    # Long-term-mean maps: ensemble median per cell
    outlets = outlet_mask(data)
    rows, cols = np.nonzero(outlets)
    fig, axes = grid(len(fields), width=3.2, height=2.9)
    for index, (axis, field) in enumerate(zip(axes, fields)):
        median = np.median(data["maps"][:, index], axis=0)
        if median.min() < -near_zero < near_zero < median.max():
            limit = np.abs(median).max()
            image = axis.imshow(median, cmap="RdBu", vmin=-limit, vmax=limit)
        else:
            image = axis.imshow(median, cmap="Blues")
        axis.scatter(cols, rows, marker="*", s=60, color="black", label="sink")
        axis.set_title(field, fontsize=8)
        axis.set_xticks([])
        axis.set_yticks([])
        colourbar = fig.colorbar(image, ax=axis, fraction=0.046, pad=0.04)
        colourbar.set_label(unit_of(field), fontsize=7)
        colourbar.ax.tick_params(labelsize=7)
    fig.suptitle(
        f"Long-term mean per cell: median over {n_runs} runs (north up; stars = sinks)"
    )
    fig.tight_layout()
    save_figure(fig, figures / "08_output_median_maps.png")


def output_findings(
    responses: pd.DataFrame,
    spatial: pd.DataFrame,
    temporal: pd.DataFrame,
    health: pd.DataFrame | None,
    tolerance: float,
) -> list[str]:
    """Plain statements of what the outputs show, for summary.md.

    These are evidence, not diagnoses: they describe the ensemble's outputs so
    the Morris indices can be read against them.
    """
    n_runs = int(responses["n_runs"].iloc[0])
    lines = [f"## Output variables ({n_runs} runs)", ""]

    if health is not None and len(health):
        closed = (health["closure_percent_of_P"].abs() <= tolerance).sum()
        lines += [
            "Water balance and stores (model_health_by_run.csv):",
            "",
            f"- {closed} of {len(health)} runs close the water balance within "
            f"+/-{tolerance:g}% of rainfall; median closure "
            f"{health['closure_percent_of_P'].median():.0f}% of rainfall.",
            "- Total runoff / rainfall: median "
            f"{health['runoff_over_precipitation'].median():.2f} (range "
            f"{health['runoff_over_precipitation'].min():.2f}-"
            f"{health['runoff_over_precipitation'].max():.3g}); surface runoff / "
            f"rainfall: median {health['surface_runoff_share_of_P'].median():.2f}.",
            f"- Lower groundwater store negative in "
            f"{(health['min_lower_groundwater_mm'] < 0).sum()} of {len(health)} runs.",
            f"- Mean soil vertical flow below 1e-3 mm in "
            f"{(health['mean_soil_vertical_flow_mm'].abs() < 1e-3).sum()} of "
            f"{len(health)} runs (median "
            f"{health['mean_soil_vertical_flow_mm'].median():.2g} mm).",
            "",
        ]

    lines += ["Responses across runs (output_summary_by_response.csv):", ""]
    for _, r in responses.iterrows():
        text = (
            f"- `{r['response']}` ({r['group']}): median {r['median']:.3g} "
            f"{r['unit']}, 5-95% {r['p05']:.3g} to {r['p95']:.3g}"
        )
        if r["n_runs_negative"]:
            text += f"; negative in {r['n_runs_negative']} runs"
        if r["cv_across_runs"] < uniform_flag:
            text += f"; hardly varies across runs (CV {r['cv_across_runs']:.2g})"
        lines.append(text + ".")

    lines += ["", "Through time (output_temporal_summary.csv):", ""]
    for _, r in temporal.iterrows():
        text = (
            f"- `{r['field']}`: peak {r['peak_month']}, lowest {r['low_month']}, "
            f"seasonal range {100 * r['seasonal_range_rel']:.0f}% of the mean"
        )
        n_drifting = r["n_runs_rising"] + r["n_runs_falling"]
        if n_drifting >= 0.25 * n_runs:
            text += (
                f"; changes by more than {100 * drift_flag:.0f}% of its mean over "
                f"the period in {n_drifting} runs (rising in {r['n_runs_rising']}, "
                f"falling in {r['n_runs_falling']}; median change "
                f"{100 * r['median_drift_rel']:+.0f}%), so it is not at steady state"
            )
        if r["share_months_negative"] > 0:
            text += f"; {100 * r['share_months_negative']:.0f}% of run-months negative"
        lines.append(text + ".")

    lines += ["", "In space (output_spatial_summary.csv):", ""]
    for _, r in spatial.iterrows():
        text = (
            f"- `{r['field']}`: cells {r['cell_min']:.3g} to {r['cell_max']:.3g} "
            f"{r['unit']} (median map)"
        )
        if r["rule"] == "outlet" and np.isfinite(r["outlet_over_domain_mean"]):
            where = "at a sink" if r["max_cell_is_outlet"] else "away from the sinks"
            text += (
                f"; largest {where}; sink cells average "
                f"{r['outlet_over_domain_mean']:.3g} x the mean cell"
            )
        if np.isfinite(r["spatial_cv"]) and r["spatial_cv"] < uniform_flag:
            text += f"; spatially uniform (CV {r['spatial_cv']:.2g})"
        if r["n_runs_any_negative_cell"]:
            text += f"; negative cells in {r['n_runs_any_negative_cell']} runs"
        lines.append(text + ".")
    return [*lines, ""]


def write_output_summaries(
    problem: dict, samples, data: dict, spec: dict, tables: Path, figures: Path
) -> dict[str, pd.DataFrame]:
    """Write the run, spatial and temporal summaries of the output variables."""
    responses = output_summary_by_response(data, spec)
    spatial, by_cell = output_spatial_summary(data, spec)
    temporal, climatology = output_temporal_summary(data)
    output_responses_by_run(problem, samples, data).to_csv(
        tables / "output_responses_by_run.csv", index=False
    )
    responses.to_csv(tables / "output_summary_by_response.csv", index=False)
    spatial.to_csv(tables / "output_spatial_summary.csv", index=False)
    by_cell.to_csv(tables / "output_spatial_by_cell.csv", index=False)
    temporal.to_csv(tables / "output_temporal_summary.csv", index=False)
    climatology.to_csv(tables / "output_monthly_climatology.csv", index=False)
    plot_output_overview(data, spec, figures)
    return {"responses": responses, "spatial": spatial, "temporal": temporal}


