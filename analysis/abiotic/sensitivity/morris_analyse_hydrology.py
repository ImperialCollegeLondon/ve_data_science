def main() -> None:
    """Run the hydrology Morris screening analysis."""
    global run_name, job_config, parameter_file, results_directory
    global replicate_directory, analysis_directory
    parser = argparse.ArgumentParser(description="Hydrology Morris analysis")
    parser.add_argument(
        "--use-cache",
        action="store_true",
        help="reuse data/responses.npz instead of reading NetCDF",
    )
    parser.add_argument("--workers", type=int, default=n_workers)
    parser.add_argument(
        "--run-name",
        help=f"run name (default {run_name}); sets the job file and the "
        "out/, out/<run>_replicates and analysis/ folders",
    )
    parser.add_argument("--results-dir", type=Path, help="out/<run> (run folders)")
    parser.add_argument("--replicate-dir", type=Path, help="out/<run>_replicates")
    parser.add_argument("--analysis-dir", type=Path, help="analysis/<run>")
    parser.add_argument(
        "--job-config", type=Path, help="job file that was run (the design)"
    )
    parser.add_argument("--parameter-file", type=Path, help="bounds used for sampling")
    args = parser.parse_args()

    if args.run_name:
        run_name = args.run_name
        job_config = module_directory / "config" / f"arrayJob_config_{run_name}.toml"
        results_directory = module_directory / "out" / run_name
        replicate_directory = module_directory / "out" / f"{run_name}_replicates"
        analysis_directory = module_directory / "analysis" / run_name
    job_config = args.job_config or job_config
    parameter_file = args.parameter_file or parameter_file
    results_directory = args.results_dir or results_directory
    replicate_directory = args.replicate_dir or replicate_directory
    analysis_directory = args.analysis_dir or analysis_directory
    print(f"Run: {run_name}\n  job file: {job_config}\n  results:  {results_directory}")
    print(f"  analysis: {analysis_directory}")

    tables, figures = analysis_directory / "tables", analysis_directory / "figures"
    for folder in (tables, figures, analysis_directory / "data"):
        folder.mkdir(parents=True, exist_ok=True)

    print("1. Design check (job-file rows form Morris trajectories on the bounds)")
    problem, samples, provenance = load_design(
        job_config,
        parameter_file,
        "morris",
        log10_parameters=None,  # read from the job-file header
        levels=None,  # read from the job-file header
        run_name=run_name,
        project_root=project_root,
    )
    levels = int(provenance["settings"]["levels"])
    design_summary, parameter_ranges = design_tables(problem, provenance)
    design_summary.to_csv(tables / "design_summary.csv", index=False)
    parameter_ranges.to_csv(tables / "parameter_ranges.csv", index=False)
    print(
        f"   D = {problem['num_vars']}, r = {provenance['settings']['trajectories']}, "
        f"p = {levels}, runs = {len(samples)}"
    )

    cache = analysis_directory / "data" / "responses.npz"
    use_cache = args.use_cache and cache.exists()
    paths, health_notes = [], []
    if not use_cache:
        print("2. Run check (parameters each run used == its design row)")
        paths = find_run_outputs(results_directory, len(samples), model_output_name)
        run_check = verify_run_parameters(paths, problem, samples)
        run_check.to_csv(tables / "run_parameter_check.csv", index=False)
        n_ok = int((run_check["status"] == "ok").sum())
        print(f"   {n_ok} of {len(paths)} runs checked and match their design row")
        if n_ok < len(paths):
            print(
                "   Note: the other runs have no compiled_configuration.toml or "
                "pbs.log, so their parameters could not be checked."
            )
        print("3. Model health (water balance, stores, vertical flow)")
        health_notes = report_model_health(
            model_health_table(paths),
            tables / "model_health_by_run.csv",
            health_tolerance,
        )

    print("4. Responses on the x/y grid")
    data = load_responses(
        paths, response_spec, cache, use_cache, project_root, args.workers
    )
    if data["scalars"].shape[0] != len(samples):
        raise ValueError("Responses do not match the design size (stale cache?).")
    save_response_spec(
        response_spec, analysis_directory / "data" / "response_spec.json"
    )
    if paths and response_spec["outlet"]["method"] == "ve_routing":
        network = ve_routing_from_output(paths[0])
        drainage_table(network).to_csv(
            analysis_directory / "data" / "drainage_network.csv", index=False
        )
        for row, col, n_cells in sorted(network["sinks"], key=lambda s: -s[2]):
            print(
                f"   sink x={network['x'][col]:.1f}, y={network['y'][row]:.1f}: "
                f"{n_cells} of {network['n_upstream'].size} cells"
            )

    print("   Output variables: run, spatial and temporal summaries")
    outputs = write_output_summaries(
        problem, samples, data, response_spec, tables, figures
    )
    health_file = tables / "model_health_by_run.csv"
    health = pd.read_csv(health_file) if health_file.exists() else None

    noise = replicate_noise(
        replicate_directory,
        provenance["replicates"],
        model_output_name,
        response_spec,
        analysis_directory / "data" / "replicate_responses.npz",
        project_root,
    )
    if noise is None:
        print("   Note: no replicate run; noise floor not assessed.")

    print("5. Morris indices")
    common = dict(num_levels=levels, conf_level=conf_level, seed=random_seed)
    scalar = scalar_morris(
        problem,
        samples,
        data,
        num_resamples=num_resamples,
        threshold=screening_threshold,
        noise=noise,
        **common,
    )
    scalar.to_csv(tables / "morris_scalar_indices.csv", index=False)
    decision = screening_decision(scalar, secondary_support)
    decision.to_csv(tables / "morris_screening_decision.csv", index=False)
    stability = ranking_stability(
        problem,
        samples,
        data,
        num_levels=levels,
        n_boot=stability_bootstraps,
        top_k=top_k,
        seed=random_seed,
    )
    stability.to_csv(tables / "morris_ranking_stability.csv", index=False)
    spatial = field_morris(
        problem, samples, data, "map", num_resamples=map_num_resamples, **common
    )
    spatial.to_csv(tables / "morris_spatial_indices.csv", index=False)
    dominant = dominant_parameter_table(spatial)
    dominant.to_csv(tables / "morris_dominant_parameter_by_cell.csv", index=False)
    monthly = field_morris(
        problem, samples, data, "series", num_resamples=map_num_resamples, **common
    )
    monthly.to_csv(tables / "morris_monthly_indices.csv", index=False)

    print("6. Figures and tables: overview, then one folder per field")
    # One colour per parameter for every figure (Sobol candidates first).
    styles = morris_parameter_styles(decision)
    plot_morris_overview(scalar, styles, figures, threshold=screening_threshold).to_csv(
        tables / "morris_mu_star_rel_by_response.csv"
    )
    response_field = {r["name"]: r["variable"] for r in response_spec["responses"]}
    response_group = {r["name"]: r["group"] for r in response_spec["responses"]}
    for field, rule in response_spec["fields"].items():
        own = [n for n in response_field if response_field[n] == field]
        group = (
            "primary"
            if any(response_group[n] == "primary" for n in own)
            else "secondary"
        )
        print(f"   {group}/{field}")
        write_field_outputs(
            field,
            group,
            own,
            rule,
            problem=problem,
            samples=samples,
            data=data,
            scalar=scalar,
            spatial=spatial,
            monthly=monthly,
            dominant=dominant,
            styles=styles,
            root=analysis_directory,
            threshold=screening_threshold,
            n_top=top_map_parameters,
        )
    summary = analysis_directory / "summary.md"
    write_morris_summary(
        summary, decision, provenance, data, noise, screening_threshold
    )
    extra = ["", "## Model health", ""]
    extra += [f"- {n}" for n in health_notes] or ["- no problems detected"]
    extra += [
        "",
        f"## Ranking stability ({stability_bootstraps} trajectory resamples)",
        "",
        f"| response | parameter | median rank | 5-95% | P(top {top_k}) |",
        "|---|---|---|---|---|",
    ]
    for _, r in stability[stability["median_rank"] <= top_k + 2].iterrows():
        extra.append(
            f"| {r['response']} | {r['parameter']} | {r['median_rank']:.0f} | "
            f"{r['rank_p05']:.0f}-{r['rank_p95']:.0f} | "
            f"{r[f'prob_top{top_k}']:.2f} |"
        )
    extra += [
        "",
        *output_findings(
            outputs["responses"],
            outputs["spatial"],
            outputs["temporal"],
            health,
            health_tolerance,
        ),
    ]
    with summary.open("a", encoding="utf-8") as handle:
        handle.write("\n".join(extra) + "\n")

    print(
        decision[
            [
                "parameter",
                "n_primary_influential",
                "n_secondary_influential",
                "max_mu_star_rel_primary",
                "sobol_candidate",
            ]
        ].to_string(index=False)
    )
    print(f"\nResults: {analysis_directory}")


if __name__ == "__main__":
    main()
