def unit_of(field: str) -> str:
    """Return the unit of a field (VE output units)."""
    return field_units.get(field, "mm")


def relative(numerator, denominator):
    """Return numerator / |denominator|, or NaN when that is (near) zero."""
    denominator = np.abs(denominator)
    with np.errstate(divide="ignore", invalid="ignore"):
        return np.where(denominator > near_zero, numerator / denominator, np.nan)


def output_responses_by_run(problem: dict, samples, data: dict) -> pd.DataFrame:
    """One row per run: the constants it used (model units) and its responses."""
    table = pd.DataFrame(to_model_space(samples, problem), columns=problem["names"])
